/**
 * 단어 단위 변환
 */
function convertWord(word, mode = 'natural') {
  if (!word) return "";
  // 둥근 따옴표(’/‘) 및 하이픈(-) 포함하여 단어 분리
  const match = word.match(/^([^a-zA-Z0-9'’\-]*)([a-zA-Z0-9'’\-]+)([^a-zA-Z0-9'’\-]*)$/);
  if (!match) return word;

  const prefix = match[1] || "";
  const core = match[2];
  const suffix = match[3] || "";
  
  // 둥근 따옴표를 일반 따옴표로 변환하여 소문자로 비교
  const lower = core.replace(/[’‘]/g, "'").toLowerCase();

  let korean = "";
  if (PHONETIC_DB[lower]) {
    korean = (mode === 'clear' ? PHONETIC_DB[lower].c : PHONETIC_DB[lower].n);
  } else {
    korean = parseFallback(lower, mode);
  }

  return prefix + korean + suffix;
}

/**
 * 메인 영어 -> 한글 발음(독음) 변환
 * @param {string} text 
 * @param {string} mode 'natural' (원어민 연음) | 'clear' (또박또박)
 */
function englishToKoreanPhonetics(text, mode = 'natural') {
  if (!text || typeof text !== "string") return "";

  let working = text.trim();

  // 1. 연음 규칙 우선 치환
  for (const item of LIAISON_LIST) {
    const rep = (mode === 'clear' ? item.c : item.n);
    working = working.replace(item.p, `§§${rep}§§`);
  }

  // 2. 단어별 변환
  const parts = working.split(/(§§[^§]+§§)/g);
  const results = parts.map(part => {
    if (part.startsWith("§§") && part.endsWith("§§")) {
      return part.slice(2, -2);
    }
    const words = part.split(/(\s+)/);
    return words.map(w => {
      if (/^\s+$/.test(w)) return w;
      return convertWord(w, mode);
    }).join("");
  });

  let final = results.join("").replace(/\s+/g, " ").trim();

  // 구두점 정리
  final = final
    .replace(/ \?/g, "?")
    .replace(/ \!/g, "!")
    .replace(/ \./g, ".")
    .replace(/ \,/g, ",");

  return final;
}

