function makeHangul(cho, jung, jong = '') {
  const c = CHO_ARR.indexOf(cho);
  const u = JUNG_ARR.indexOf(jung);
  const j = JONG_ARR.indexOf(jong);
  if (c === -1 || u === -1) return (cho || '') + (jung || '') + (jong || '');
  return String.fromCharCode(0xAC00 + (c * 21 + u) * 28 + (j === -1 ? 0 : j));
}

